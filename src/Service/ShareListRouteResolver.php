<?php

declare(strict_types=1);

namespace Nowo\YopassBundle\Service;

use JsonException;
use Nowo\YopassBundle\Event\ShareListRouteEvent;
use Nowo\YopassBundle\Event\YopassEvents;
use Nowo\YopassBundle\Ui\ListRoute;
use Symfony\Component\HttpFoundation\Request;
use Symfony\Component\Security\Core\User\UserInterface;
use Symfony\Contracts\EventDispatcher\EventDispatcherInterface;

use function array_is_list;
use function base64_decode;
use function base64_encode;
use function count;
use function explode;
use function hash_equals;
use function hash_hmac;
use function in_array;
use function is_array;
use function is_scalar;
use function is_string;
use function json_decode;
use function json_encode;
use function rtrim;
use function strlen;
use function strtr;

use const JSON_THROW_ON_ERROR;

/**
 * Resolves the page that shows the manage list (pager, filter form, post-action redirects) and carries it through the
 * row / toolbar action forms as a token.
 *
 * Security (REQ-SEC-004): no free URL is ever accepted. The token holds a route name + scalar parameters, is signed
 * with HMAC-SHA256 for the viewer that rendered the list — the key is the raw `kernel.secret`, the message is the
 * fixed label `nowo_yopass.list_route|` + the viewer's `getUserIdentifier()` + the payload — and is accepted only when
 * the signature matches the current viewer (same user identifier) and the route is the manage route or listed in
 * `nowo_yopass.web_ui.list_routes`. Anything else falls back to the manage route. The redirect URL is generated by the
 * router (a same-host path).
 */
final readonly class ShareListRouteResolver
{
    /** Name of the hidden field of the action forms. */
    public const FIELD = '_list';

    private const MAX_TOKEN_LENGTH = 2048;

    /** @var list<string> */
    private array $allowedRoutes;

    /**
     * @param string $manageRoute Name of the bundle's manage route (`nowo_yopass.routes.manage.name`)
     * @param array<mixed> $listRoutes Extra host routes allowed as list page (`nowo_yopass.web_ui.list_routes`)
     * @param string $secret `kernel.secret` (empty = tokens disabled: actions redirect to the manage route)
     */
    public function __construct(
        private string $manageRoute,
        array $listRoutes = [],
        private string $secret = '',
        private ?EventDispatcherInterface $eventDispatcher = null,
    ) {
        $allowed = [$manageRoute];
        foreach ($listRoutes as $route) {
            if (is_string($route) && $route !== '' && !in_array($route, $allowed, true)) {
                $allowed[] = $route;
            }
        }
        $this->allowedRoutes = $allowed;
    }

    /**
     * The bundle's manage route (the default list page).
     */
    public function defaultRoute(): ListRoute
    {
        return new ListRoute($this->manageRoute);
    }

    /**
     * Resolves the list page for a list request (dispatches {@see YopassEvents::SHARE_LIST_ROUTE}).
     */
    public function resolve(UserInterface $viewer, Request $request): ListRoute
    {
        $event = new ShareListRouteEvent($viewer, $request, $this->defaultRoute(), $this->allowedRoutes);
        $this->eventDispatcher?->dispatch($event, YopassEvents::SHARE_LIST_ROUTE);

        return $event->getRoute();
    }

    /**
     * Token carried by the action forms, or null when it is not needed (manage route) or tokens are disabled.
     */
    public function sign(UserInterface $viewer, ListRoute $route): ?string
    {
        if ($this->secret === '' || ($route->name === $this->manageRoute && $route->params === [])) {
            return null;
        }

        $payload = $this->base64UrlEncode(json_encode([$route->name, $route->params], JSON_THROW_ON_ERROR));

        return $payload . '.' . $this->signature($viewer, $payload);
    }

    /**
     * The list page an action redirects to: the verified token's route, else the manage route.
     */
    public function fromToken(UserInterface $viewer, mixed $token): ListRoute
    {
        return $this->verify($viewer, $token) ?? $this->defaultRoute();
    }

    private function verify(UserInterface $viewer, mixed $token): ?ListRoute
    {
        if ($this->secret === '' || !is_string($token) || $token === '' || strlen($token) > self::MAX_TOKEN_LENGTH) {
            return null;
        }

        $parts = explode('.', $token);
        if (count($parts) !== 2 || !hash_equals($this->signature($viewer, $parts[0]), $parts[1])) {
            return null;
        }

        try {
            $decoded = json_decode($this->base64UrlDecode($parts[0]), true, 4, JSON_THROW_ON_ERROR);
        } catch (JsonException) {
            return null;
        }

        if (!is_array($decoded) || !array_is_list($decoded) || count($decoded) !== 2) {
            return null;
        }

        [$name, $params] = $decoded;
        if (!is_string($name) || !in_array($name, $this->allowedRoutes, true) || !is_array($params)) {
            return null;
        }

        $clean = [];
        foreach ($params as $key => $value) {
            if (!is_string($key) || !is_scalar($value)) {
                return null;
            }
            $clean[$key] = $value;
        }

        return new ListRoute($name, $clean);
    }

    private function signature(UserInterface $viewer, string $payload): string
    {
        // Bound to the viewer: a token rendered for one user is useless to another.
        return $this->base64UrlEncode(hash_hmac('sha256', 'nowo_yopass.list_route|' . $viewer->getUserIdentifier() . '|' . $payload, $this->secret, true));
    }

    private function base64UrlEncode(string $value): string
    {
        return rtrim(strtr(base64_encode($value), '+/', '-_'), '=');
    }

    private function base64UrlDecode(string $value): string
    {
        return (string) base64_decode(strtr($value, '-_', '+/'), true);
    }
}
